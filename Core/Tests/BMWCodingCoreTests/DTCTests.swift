import Testing
@testable import BMWCodingCore

@Test func parsesBMWFaultRecords() {
    let payload: [UInt8] = [0x59, 0x02, 0xFF, 0x80, 0x1E, 0x2B, 0x2F, 0xB1, 0xF3, 0xE0, 0x08, 0x12]
    #expect(DTCParse.bmwFaults(payload) == [DTC(code: "801E2B", status: 0x2F), DTC(code: "B1F3E0", status: 0x08)])
    #expect(DTCParse.bmwFaults([0x59, 0x02, 0xFF]) == [])
    #expect(DTCParse.bmwFaults([0x59, 0x02]) == nil)
    #expect(DTCParse.bmwFaults([0x62, 0x30, 0x00]) == nil)
}
@Test func decodesStandardCodes() {
    #expect(DTCParse.obdCode(0x04, 0x20) == "P0420")
    #expect(DTCParse.obdCode(0x41, 0x23) == "C0123")
    #expect(DTCParse.obdCode(0x93, 0xA1) == "B13A1")
    #expect(DTCParse.obdCode(0xC1, 0x00) == "U0100")
    #expect(DTCParse.obdCodes([0x43, 0x02, 0x04, 0x20, 0xC1, 0x00, 0x00, 0x00]) == ["P0420", "U0100"])
    #expect(DTCParse.obdCodes([0x47, 0x00]) == [])
    #expect(DTCParse.obdCodes([0x41, 0x00]) == nil)
}
@Test func readsSupportedPIDs() {
    #expect(DTCParse.supportedPIDs([0x41, 0x00, 0x80, 0x00, 0x00, 0x01], base: 0x00) == [0x01, 0x20])
    #expect(DTCParse.supportedPIDs([0x41, 0x20, 0x00, 0x00, 0x00, 0x00], base: 0x20) == [])
    #expect(DTCParse.supportedPIDs([0x41, 0x00, 0x80], base: 0x00) == nil)
    #expect(DTCParse.supportedPIDs([0x41, 0x20, 0x80, 0x00, 0x00, 0x00], base: 0x00) == nil)
}
@Test func bmwFaultsNeedTheListSubfunction() {
    #expect(DTCParse.bmwFaults([0x59, 0x01, 0xFF, 0x80, 0x1E, 0x2B, 0x2F]) == nil)
    #expect(DTCParse.bmwFaults([]) == nil)
}
@Test func ignoresTheOBDCodeCount() {
    #expect(DTCParse.obdCodes([0x43, 0x01, 0x04, 0x20, 0xC1, 0x00]) == ["P0420", "U0100"])  // the count says one
    #expect(DTCParse.obdCodes([0x43, 0x09, 0x04, 0x20]) == ["P0420"])  // the count says nine
    #expect(DTCParse.obdCodes([0x43, 0x02, 0x04, 0x20, 0xC1]) == ["P0420"])  // half a pair at the end
    #expect(DTCParse.obdCodes([0x43]) == nil)  // a lone service byte is garbled, not "no codes"
    #expect(DTCParse.obdCodes([]) == nil)
}
@Test func readsEveryFlagOfASupportedPIDAnswer() {
    let answer: [UInt8] = [0x41, 0x00, 0xBE, 0x1F, 0xA8, 0x13]
    #expect(DTCParse.supportedPIDs(answer, base: 0x00)
        == [0x01, 0x03, 0x04, 0x05, 0x06, 0x07, 0x0C, 0x0D, 0x0E, 0x0F, 0x10, 0x11, 0x13, 0x15, 0x1C, 0x1F, 0x20])
    #expect(DTCParse.supportedPIDs([0x41, 0x40, 0x40, 0x00, 0x00, 0x00], base: 0x40) == [0x42])  // bit 6 is base + 2
    #expect(DTCParse.supportedPIDs([0x41, 0x00, 0x80, 0x00, 0x00, 0x00, 0x00], base: 0x00) == nil)  // a byte too many
}
@Test func dropsSupportedPIDsThatDoNotFitAByte() {
    let everything: [UInt8] = [0x41, 0xE0, 0xFF, 0xFF, 0xFF, 0xFF]
    #expect(DTCParse.supportedPIDs(everything, base: 0xE0) == [UInt8](0xE1...0xFF))  // PID 0x100 is dropped
}
